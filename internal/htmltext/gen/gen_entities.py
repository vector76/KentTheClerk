"""Generate ../entities_gen.go from the running interpreter's html.entities.html5.

Run from internal/htmltext:  python -I gen/gen_entities.py -o entities_gen.go
(go generate does this through the //go:generate line in unescape.go); without -o it writes stdout.
The table must come from CPython 3.13's html.entities so the Go port matches it byte for byte.
The output is already gofmt-clean (one {key, value} pair per line, nothing to align).
"""
import sys
from html.entities import html5


def golit(s: str) -> str:
    out = ['"']
    for ch in s:
        c = ord(ch)
        if ch == '"' or ch == "\\":
            out.append("\\" + ch)
        elif 0x20 <= c < 0x7F:
            out.append(ch)
        elif c <= 0xFFFF:
            out.append("\\u%04x" % c)
        else:
            out.append("\\U%08x" % c)
    out.append('"')
    return "".join(out)


def main() -> None:
    if len(sys.argv) == 3 and sys.argv[1] == "-o":
        f = open(sys.argv[2], "w", newline="\n", encoding="utf-8")
    else:
        sys.stdout.reconfigure(newline="\n", encoding="utf-8")
        f = sys.stdout
    w = f.write
    w("// Code generated by gen/gen_entities.py from CPython %d.%d.%d html.entities.html5; DO NOT EDIT.\n\n"
      % sys.version_info[:3])
    w("package htmltext\n\n")
    w("// html5 mirrors html.entities.html5: %d named character references.\n" % len(html5))
    w("var html5 = make(map[string]string, len(html5Pairs))\n\n")
    w("func init() {\n\tfor _, kv := range html5Pairs {\n\t\thtml5[kv[0]] = kv[1]\n\t}\n}\n\n")
    w("var html5Pairs = [...][2]string{\n")
    for k in sorted(html5):
        w("\t{%s, %s},\n" % (golit(k), golit(html5[k])))
    w("}\n")
    f.flush()


if __name__ == "__main__":
    main()
